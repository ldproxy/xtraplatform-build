package de.interactive_instruments.xtraplatform

import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity

/**
 * Non-Java components of a module that the CycloneDX plugin cannot detect.
 *
 * <pre>
 * sbom {
 *     component name: 'zlib', version: zlibVersion, license: 'Zlib', cpe: "cpe:2.3:a:zlib:zlib:${zlibVersion}:*:*:*:*:*:*:*"
 *     component name: 'proj', version: projVersion, license: 'MIT', dependsOn: ['sqlite', 'libtiff']
 *     fragment tasks.named('npmSbom')
 * }
 * </pre>
 *
 * component keys: name, version (required), group, type, description, purl, cpe, license (SPDX id, list of ids or expression),
 * url (download), website, vcs, sha256, dependsOn (names of other components of this module)
 *
 * fragment: CycloneDX 1.6 JSON files, e.g. generated by cyclonedx-gomod or cyclonedx-npm
 */
abstract class SbomExtension {

    @Input
    abstract Property<String> getModulePath()

    @Input
    abstract ListProperty<Map<String, Object>> getComponents()

    @InputFiles
    @PathSensitive(PathSensitivity.NONE)
    abstract ConfigurableFileCollection getFragments()

    void component(Map<String, Object> component) {
        getComponents().add(normalize(component) as Map<String, Object>)
    }

    void fragment(Object source) {
        getFragments().from(source)
    }

    // GStrings are not stable task inputs
    private static Object normalize(Object value) {
        if (value instanceof Map) {
            return value.collectEntries { k, v -> [(k.toString()): normalize(v)] }
        }
        if (value instanceof Collection) {
            return value.collect { normalize(it) }
        }
        return value == null ? null : value.toString()
    }
}
